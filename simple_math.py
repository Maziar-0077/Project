def multiplication(x: float, y: float) -> float:
    return x * y

print('multiplication')
x = float(input('Enter First Digit:'))
y = float(input('Enter Second Digit:'))
print(multiplication(x, y))


def power(x: float, y: float) -> float:
    return x ** y

print('power')
x = float(input('Enter First Digit:'))
y = float(input('Enter Second Digit:'))
print(power(x, y))
